// Converts research.json -> data.js (what the page loads). Run: node build-data.js
const fs = require('fs');
// research.json is the base; any research-*.json files are merged in (dedupe by name+address).
const r = JSON.parse(fs.readFileSync(__dirname + '/research.json', 'utf8'));
fs.readdirSync(__dirname).filter((f) => /^research-.*\.json$/.test(f)).sort().forEach((f) => {
  const extra = JSON.parse(fs.readFileSync(__dirname + '/' + f, 'utf8'));
  const seen = new Set(r.places.map((p) => (p.name + '|' + p.address).toLowerCase()));
  (extra.places || []).forEach((p) => { const k = (p.name + '|' + p.address).toLowerCase(); if (!seen.has(k)) { r.places.push(p); seen.add(k); } });
  (extra.chains || []).forEach((c) => { if (!r.chains.some((x) => x.brand === c.brand)) r.chains.push(c); });
});
const CAT_MAP = [
  [/congee|porridge|粥|juk/i, 'congee'],
  [/udon|noodle|面|ramen|pho|soup/i, 'noodle'],
  [/soy|豆浆|breakfast|taiwan|shanghai|饭团/i, 'soymilk'],
  [/bakery|bun|包|bread|烘焙|bagel/i, 'bakery'],
  [/grocery|market|supermarket|超市|便利|deli|pharmacy|cvs|mart/i, 'grocery'],
];
function cats(p) {
  const set = new Set(p.cats || []);
  if (!set.size) {
    const hay = [p.name, p.name_zh, p.type, p.category].join(' ');
    CAT_MAP.forEach(([re, c]) => { if (re.test(hay)) set.add(c); });
  }
  // late: open past 23:00 or 24/7
  if (/24\s*\/\s*7/.test(p.hours || '') || /-(0[0-5]|23|24):\d\d/.test(p.hours || '')) set.add('late');
  return [...set];
}
const places = (r.places || []).filter((p) => p.lat && p.lng && p.hours).map((p, i) => ({
  id: 'p' + (i + 1),
  name: p.name, name_local: p.name_local || '', address: p.address, neighborhood: p.neighborhood || '',
  lat: +(+p.lat).toFixed(5), lng: +(+p.lng).toFixed(5),
  hours: p.hours, tier: p.tier || (/congee|porridge|juk|粥/i.test(p.name + ' ' + (p.type || '')) ? 'safe' : 'ok'),
  cats: cats(p), buy: p.buy || [], avoid: p.avoid || '', confidence: p.confidence || 'medium', source: p.source || '', notes: p.notes || '',
}));
const chains = (r.chains || []).map((c) => ({ brand: c.brand, note: c.note || '', buy: c.buy || [], avoid: c.avoid || [] }));
const out = '/* generated by build-data.js from research.json — edit research.json, not this file */\n' +
  'window.PLACES = ' + JSON.stringify(places) + ';\nwindow.CHAINS = ' + JSON.stringify(chains) + ';\n';
fs.writeFileSync(__dirname + '/data.js', out);
console.log('places:', places.length, 'chains:', chains.length);
console.log('cats:', places.reduce((m, p) => { p.cats.forEach((c) => (m[c] = (m[c] || 0) + 1)); return m; }, {}));
